// Run from the project folder: node tests/demo.test.js
const ts=require('typescript');const fs=require('fs');
const strip=s=>s.replace(/import [^;]*;\n/g,'').replace(/^export /gm,'');
const src=strip(fs.readFileSync('lib/phone.ts','utf8'))+'\n'+strip(fs.readFileSync('lib/demo.ts','utf8'));
const js=ts.transpileModule(src,{compilerOptions:{target:'es2020',module:'commonjs'}}).outputText+'\nmodule.exports={validateDemo,looksAutomated,BUSINESS_TYPES};';
const m={exports:{}};new Function('module','exports',js)(m,m.exports);
const {validateDemo,looksAutomated}=m.exports;
let fails=0;const ok=(n,c)=>{if(!c){fails++;console.log('FAIL',n)}};
const good={name:'Sam Rivera',business:'Rivera Cuts',email:'Sam@Example.com ',phone:'(612) 555-0123',businessType:'Salon or barbershop',message:'Answer calls while I cut hair',consent:true,source:'instagram / paid / fall'};
let r=validateDemo(good);
ok('a good request passes',r.ok);
ok('email tidied to lowercase',r.value.email==='sam@example.com');
ok('phone normalized',r.value.phone==='+16125550123');
ok('source kept',r.value.source==='instagram / paid / fall');
r=validateDemo({...good,phone:''});ok('phone is optional',r.ok&&r.value.phone===null);
r=validateDemo({...good,message:''});ok('message is optional',r.ok&&r.value.message===null);
r=validateDemo({...good,consent:false});ok('consent required',!r.ok&&r.errors.some(e=>e.includes('agree')));
r=validateDemo({...good,consent:'true'});ok('consent must be a real yes, not text',!r.ok);
r=validateDemo({...good,email:'not-an-email'});ok('bad email refused',!r.ok&&r.errors.some(e=>e.includes('email')));
r=validateDemo({...good,phone:'123'});ok('bad phone refused with a helpful note',!r.ok&&r.errors.some(e=>e.includes('leave it empty')));
r=validateDemo({...good,businessType:'Hacker'});ok('unknown business type refused',!r.ok);
r=validateDemo({});ok('empty form lists every problem',!r.ok&&r.errors.length===5);
r=validateDemo({...good,name:'Sam\u0000\u0007 Rivera',business:'x'.repeat(500)});ok('control characters removed and long text cut',r.ok&&r.value.name==='Sam Rivera'&&r.value.business.length===120);
const now=Date.now();
ok('real person passes',!looksAutomated({startedAt:now-20000,website:''},now));
ok('hidden field filled = bot',looksAutomated({startedAt:now-20000,website:'http://spam'},now));
ok('too fast = bot',looksAutomated({startedAt:now-1000},now));
ok('missing timer = bot',looksAutomated({},now));
ok('stale page from days ago = bot',looksAutomated({startedAt:now-3*86400000},now));
console.log(fails?'FAILED '+fails:'all demo form checks pass');
